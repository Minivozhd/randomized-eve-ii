MagicOptionsDialog::MagicOptionsDialog(std::shared_ptr<UIContext> _ctx, Header *_header)
    : wxFrame(NULL, wxID_ANY, _MAGIC_OPTIONS_DIALOG_TITLE_STR, wxDefaultPosition,
              wxSize(_MAGIC_OPTIONS_DIALOG_WIDTH, _MAGIC_OPTIONS_DIALOG_HEIGHT)),
      ctx(_ctx), header(_header) {
    panel = new wxPanel(this, wxID_ANY);
    dialog_sizer = new wxBoxSizer(wxVERTICAL);
    dialog_inner_sizer = new wxBoxSizer(wxVERTICAL);

    panel->SetSizer(dialog_sizer);
    dialog_sizer->Add(dialog_inner_sizer, 1, wxEXPAND | wxALL, 25);

    ctx_copy = UIContext(0, ctx->logger);
    ctx_copy.spell_cost_mult = _ctx->spell_cost_mult;
    ctx_copy.spell_start_option = _ctx->spell_start_option;

    DrawMagicOptions();
    ui::fitContent(this, panel);
}

void MagicOptionsDialog::OnClose(wxCloseEvent &event) {
    (void)event;
    Destroy();
}

void MagicOptionsDialog::OnAccept(wxCommandEvent &event) {
    (void)event;
    int selected_index = magic_combobox->GetSelection();
    uint8_t selection = 0;
    if (selected_index != wxNOT_FOUND) {
        selection = (uint8_t)selected_index;
    }
    ctx_copy.spell_start_option = selection;

    ctx->spell_cost_mult = ctx_copy.spell_cost_mult;
    ctx->spell_start_option = ctx_copy.spell_start_option;
    header->redrawContext();
    Destroy();
}

void MagicOptionsDialog::OnCancel(wxCommandEvent &event) {
    (void)event;
    Destroy();
}

void MagicOptionsDialog::OnDefault(wxCommandEvent &event) {
    (void)event;
    ctx_copy.spell_cost_mult = 100;
    spell_cost_mult->SetValue("1.00");

    magic_combobox->SetSelection(0);
    ctx_copy.spell_start_option = 0;
}

void MagicOptionsDialog::OnMagicCostMultChange(wxCommandEvent &event) {
    (void)event;
    wxString value_str = spell_cost_mult->GetValue();
    double double_value;
    value_str.ToDouble(&double_value);
    ctx_copy.spell_cost_mult = (uint16_t)(double_value * 100);
}

void MagicOptionsDialog::DrawMagicOptions() {
    wxBoxSizer *cost_mult_sizer = new wxBoxSizer(wxHORIZONTAL);
    spell_cost_mult = new wxTextCtrl(panel, wxID_ANY,
                                     wxString::Format(wxT("%.2lf"), ((double)ctx_copy.spell_cost_mult / 100)),
                                     wxDefaultPosition, wxDefaultSize, 0, DoubleValidator());
    spell_cost_mult->Bind(wxEVT_TEXT, &MagicOptionsDialog::OnMagicCostMultChange, this);

    wxStaticText *cost_mult_input_label =
        new wxStaticText(panel, wxID_ANY, _MAGIC_OPTIONS_SPELL_COST_LABEL_STR);
    wxStaticText *cost_mult_tip = new wxStaticText(panel, wxID_ANY, wxT("[?]"));
    cost_mult_tip->SetForegroundColour(*wxBLUE);
    cost_mult_tip->SetToolTip(_MAGIC_OPTIONS_SPELL_COST_TIP_STR);

    cost_mult_sizer->Add(cost_mult_input_label, 1, wxEXPAND, 0);
    cost_mult_sizer->Add(cost_mult_tip, 1, wxEXPAND, 0);
    cost_mult_sizer->Add(spell_cost_mult, 1, wxALL, 0);

    wxBoxSizer *spell_randomization_sizer = new wxBoxSizer(wxHORIZONTAL);
    wxArrayString items;
    for (const std::string &item : _MAGIC_OPTIONS_COMBOBOX_ITEMS) {
        items.Add(item);
    }
    wxStaticText *magic_combobox_label =
        new wxStaticText(panel, wxID_ANY, _MAGIC_OPTIONS_STARTING_SPELL_LABEL_STR);
    wxStaticText *magic_combobox_tip = new wxStaticText(panel, wxID_ANY, wxT("[?]"));
    magic_combobox_tip->SetForegroundColour(*wxBLUE);
    magic_combobox_tip->SetToolTip(_MAGIC_OPTIONS_STARTING_SPELL_TIP_STR);
    magic_combobox =
        new wxComboBox(panel, wxID_ANY, _MAGIC_OPTIONS_COMBOBOX_ITEMS[ctx_copy.spell_start_option],
                       wxDefaultPosition, wxSize(180, -1), items, wxCB_READONLY);

    spell_randomization_sizer->Add(magic_combobox_label, 1, wxEXPAND | wxALL, 0);
    spell_randomization_sizer->Add(magic_combobox_tip, 1, wxEXPAND | wxALL, 0);
    spell_randomization_sizer->Add(magic_combobox, 1, wxEXPAND | wxALL, 0);

    dialog_inner_sizer->Add(cost_mult_sizer, 1, wxEXPAND | wxALL, 0);
    dialog_inner_sizer->Add(spell_randomization_sizer, 1, wxEXPAND | wxALL, 0);

    wxBoxSizer *buttons_sizer = new wxBoxSizer(wxHORIZONTAL);
    wxButton *apply_button = new wxButton(panel, wxID_OK, wxT("Apply"));
    apply_button->Bind(wxEVT_BUTTON, &MagicOptionsDialog::OnAccept, this);
    buttons_sizer->Add(apply_button, 0, wxRIGHT, 5);

    wxButton *cancel_button = new wxButton(panel, wxID_OK, wxT("Cancel"));
    cancel_button->Bind(wxEVT_BUTTON, &MagicOptionsDialog::OnCancel, this);
    buttons_sizer->Add(cancel_button, 0, wxCENTER, 5);

    wxButton *default_button = new wxButton(panel, wxID_OK, wxT("Default"));
    default_button->Bind(wxEVT_BUTTON, &MagicOptionsDialog::OnDefault, this);
    buttons_sizer->Add(default_button, 0, wxLEFT, 5);

    dialog_inner_sizer->Add(buttons_sizer, 0, wxEXPAND, 5);
}
